package com.roleorienta.api.vacancy;

/**
 * Статус вакансии у пользователя, который пишется в историю (бизнес-описание §6; стенограмма §156). «Новая» — не
 * событие: это отсутствие текущего статуса; «Получена» и «Закрыта работодателем» не хранятся — их собирает API.
 */
public enum StatusEvent {

    /** «Просмотрена» — ставит приложение, когда пользователь открыл публикацию новой вакансии из результатов (§193). */
    VIEWED(false),
    /** «Не интересно» — вакансия уходит в раздел «Не интересно». */
    NOT_INTERESTED(false),
    /** «Отклик отправлен» (§199) — в «Мои отклики». */
    APPLIED(true),
    /** «Собеседование» — в «Мои отклики». */
    INTERVIEW(true),
    /** «Работодатель отказал» (§195) — в «Мои отклики», ниже и свёрнуто (§196). */
    REJECTED(true),
    /** «Возвращена» из «Не интересно» или из «Отклик отправлен» (§200): строка истории, текущим не бывает. */
    RETURNED(false);

    private final boolean response;

    StatusEvent(boolean response) {
        this.response = response;
    }

    /**
     * @return {@code true} — статус отклика («Мои отклики»): в тот же день заменяет статус отклика (исправление
     *         ошибочного нажатия, решение владельца 2026-10-21). «Не интересно» не заменяет и не заменяется — иначе
     *         «Вернуть» не нашло бы в истории прежний статус (аудит §165)
     */
    public boolean response() {
        return response;
    }
}

package com.roleorienta.api.vacancy;

/**
 * Группа «Моих откликов» (решение владельца 2026-10-28, стенограмма §217): сверху то, с чем идёт работа, ниже свёрнуто —
 * то, где ответа давно нет, и завершённое. Отклик без ответа {@value #SILENT_DAYS} дней — «Нет ответа 3+ недели»,
 * {@value #GIVE_UP_DAYS} дней — среди завершённых: так долго молчащий работодатель почти никогда уже не отвечает, а
 * список откликов не разрастается. Новый статус (или снова «Отклик отправлен») возвращает отклик наверх: срок — от
 * даты текущего статуса.
 */
public enum ResponseGroup {

    /** Действующие: «Собеседование» и «Отклик отправлен» моложе {@value #SILENT_DAYS} дней по открытым вакансиям. */
    ACTIVE,
    /**
     * «Нет ответа 3+ недели»: «Отклик отправлен» {@value #SILENT_DAYS}–{@value #GIVE_UP_DAYS} дней назад по открытой
     * вакансии.
     */
    SILENT,
    /**
     * Завершённые (§196, §213): «Работодатель отказал», отклики по вакансиям, закрытым работодателем, и «Отклик
     * отправлен» {@value #GIVE_UP_DAYS} дней назад и раньше.
     */
    FINISHED;

    /**
     * Сколько дней без ответа, прежде чем отклик уходит в «Нет ответа 3+ недели»; то же число — у подписи «No reply for
     * N days» в web ({@code NO_REPLY_DAYS}, §216).
     */
    public static final int SILENT_DAYS = 21;

    /** Сколько дней без ответа, прежде чем отклик уходит в завершённые. */
    public static final int GIVE_UP_DAYS = 42;
}

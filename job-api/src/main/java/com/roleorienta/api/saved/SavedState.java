package com.roleorienta.api.saved;

/**
 * Отношение пользователя к публикации (§7): сохранил для себя или скрыл.
 *
 * <p>Значения взаимоисключающие — это состояние одной строки-маркера
 * {@code saved_posting} (пара «пользователь × публикация»). Хранится строкой
 * ({@code @Enumerated(EnumType.STRING)}), как остальные перечисления проекта
 * (см. V3/V14): читаемо в базе и устойчиво к перестановке значений.</p>
 */
public enum SavedState {

    /** Публикация сохранена пользователем (интересна, вернуться позже). */
    SAVED,

    /** Публикация скрыта пользователем (не интересна; причина — в {@code hidden_reason}). */
    HIDDEN
}

package com.roleorienta.api.auth;

/**
 * Роль пользователя (§7.9): обычный пользователь и администратор/куратор.
 *
 * <p>Хранится строкой (см. {@link AppUser}). Права по ролям задаёт
 * {@code SecurityConfig}; куратор не получает автоматического доступа к личным
 * данным других пользователей (§9, A23) — это обеспечивается проверками владельца
 * при появлении персональных сущностей, а не самой ролью.</p>
 */
public enum UserRole {

    /** Обычный пользователь: свои подписки, заметки, отклики. */
    USER,

    /** Администратор/куратор: подтверждение источников, разбор отчётов, курирование. */
    ADMIN
}

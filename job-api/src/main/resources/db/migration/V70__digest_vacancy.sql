-- Вакансии, уже попавшие в сводку на почту (аудит §165; решение владельца 2026-10-21). Заменяет границу
-- user_account.digest_sent_until — момент выдачи последней вакансии письма: граница по времени теряла вакансии, если
-- выдача фиксировалась позже письма с меткой времени раньше границы, и повторяла их, если выдача фиксировалась между
-- подсчётом и чтением строк письма. Теперь в письмо идёт всё выданное и видимое в результатах, чего здесь ещё нет, и
-- отметка пишется тем же запросом, что отбирает вакансии письма. Вакансия приходит в письме один раз, и после смены
-- условий поиска (новая версия условий выдаёт её заново).
--   mailed_at — когда вакансия попала в письмо.
CREATE TABLE digest_vacancy (
    user_id    BIGINT      NOT NULL REFERENCES user_account (id),
    vacancy_id BIGINT      NOT NULL REFERENCES vacancy (id),
    mailed_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, vacancy_id)
);

ALTER TABLE user_account DROP COLUMN digest_sent_until;

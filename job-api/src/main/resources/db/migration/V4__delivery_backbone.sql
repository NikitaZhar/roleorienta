-- V4 — идемпотентность потребителя фоновых заданий (ADR-3, §8 техдока).
--
-- Доставка сообщений имеет семантику at-least-once: одно и то же сообщение
-- может прийти повторно (повтор после сетевого разрыва, перезапуск обработчика,
-- восстановление брокера). Перед обработкой потребитель фиксирует ключ
-- идемпотентности в этой таблице; повторная доставка не проходит из-за
-- первичного ключа (INSERT ... ON CONFLICT DO NOTHING возвращает 0 строк) и
-- становится no-op. Таблица инфраструктурная, к доменным сущностям не относится.

CREATE TABLE processed_message (
    -- Ключ идемпотентности сообщения (messageId = id исходного outbox-события).
    idempotency_key TEXT        PRIMARY KEY,
    -- Момент первичной обработки (UTC). Служит для наблюдаемости и последующей
    -- политики очистки старых записей (вводится отдельно при необходимости).
    processed_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Словарь позиций в БД (стенограмма §159; решение владельца 2026-10-21): раньше — файл positions.json воркера,
-- теперь его редактирует администратор (срез 6б). Данные перенесены из positions.json версии 2026-10-16.1 один к одному.
--
-- position_term — названия позиции по видам: TITLE — эквивалентное название; ROLE — роль в названии (developer,
-- engineer …); KEYWORD — признак специализации (в названии вместе с ролью или в тексте); EXCLUDE — слово названия,
-- исключающее позицию. Слова хранятся как записаны; регистр и диакритику убирает воркер при сопоставлении.
CREATE TABLE position_term (
    id          BIGSERIAL    PRIMARY KEY,
    position_id BIGINT       NOT NULL REFERENCES position (id),
    kind        VARCHAR(10)  NOT NULL CHECK (kind IN ('TITLE', 'ROLE', 'KEYWORD', 'EXCLUDE')),
    term        VARCHAR(100) NOT NULL CHECK (btrim(term) <> '')
);

-- Одно слово одного вида у позиции — один раз (без учёта регистра); поиск названий позиции — по этому индексу.
CREATE UNIQUE INDEX position_term_unique_idx ON position_term (position_id, kind, lower(term));

-- position_dictionary — общие настройки словаря, одна строка (id = 1): version — номер версии, растёт при каждом
-- изменении словаря и входит в версию сопоставления («d<номер>»): любое изменение пересчитывает вакансии;
-- content_hits — сколько раз признак специализации должен встретиться в тексте при роли в названии;
-- other_specializations — признаки специализаций вне словаря (при них в названии правило по тексту не применяется).
CREATE TABLE position_dictionary (
    id                    SMALLINT PRIMARY KEY CHECK (id = 1),
    version               INTEGER  NOT NULL CHECK (version > 0),
    content_hits          INTEGER  NOT NULL CHECK (content_hits > 0),
    other_specializations TEXT[]   NOT NULL
);


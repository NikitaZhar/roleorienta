-- Показатели ядра по дням (бизнес-описание §7.3; технический документ §11; стенограмма §131): строка — значение
-- показателя за день по стране и разрезу. Пересчёт дня заменяет все его строки.
--   country   — код страны ISO 3166-1 alpha-2; '*' — весь мир (вакансии «удалённо без ограничения территории»);
--               '' — страна вакансии не определена или показатель не относится к стране (операции);
--   metric    — код показателя (список — технический документ §11);
--   dimension — разрез: '' — итог показателя; иначе значение разреза (способ подтверждения сайта, система найма,
--               причина неудачи, доступность или итог чтения источника, тип задания).
CREATE TABLE core_metric_daily (
    day         DATE        NOT NULL,
    country     VARCHAR(2)  NOT NULL,
    metric      VARCHAR(40) NOT NULL,
    dimension   VARCHAR(60) NOT NULL,
    value       BIGINT      NOT NULL,
    computed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (day, country, metric, dimension)
);

package com.roleorienta.core.domain;

/**
 * Состояние покрытия публикации площадками (A5, ADR-15, A01) — результат процедуры сравнения,
 * а не факт отсутствия.
 *
 * <p>{@code UNKNOWN} — не проверено или проверка неполна (площадка недоступна, обход неполон,
 * сопоставление неоднозначно); так же трактуется публикация без записи оценки.
 * {@code SITE_ONLY} — «скрытая»: не найдена на проверенных площадках при проверке [дата];
 * {@code ON_PLATFORM} — найдена на площадке, на сайте работодателя не найдена;
 * {@code BOTH} — и там, и там.</p>
 */
public enum CoverageState {
    UNKNOWN,
    SITE_ONLY,
    ON_PLATFORM,
    BOTH
}

package com.roleorienta.core.domain;

/**
 * Уверенность обнаружения по результату проверки ленты кандидата (§5, гейт
 * уверенности).
 *
 * <p>{@code HIGH} — лента валидна и непуста (принадлежность правдоподобна);
 * {@code LOW} — лента валидна, но пуста/неоднозначна (пустая валидная доска не
 * обязательно ложна — нужна проверка человеком); {@code NONE} — ленту не удалось
 * прочитать или разобрать. В этом срезе уверенность лишь информирует
 * администратора: авто-подключение по гейту — следующий срез, все кандидаты идут
 * в очередь.</p>
 */
public enum DiscoveryConfidence {
    HIGH,
    LOW,
    NONE
}

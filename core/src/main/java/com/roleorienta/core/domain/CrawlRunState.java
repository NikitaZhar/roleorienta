package com.roleorienta.core.domain;

/**
 * Состояние обхода источника ({@link CrawlRun}).
 *
 * <p>На этапе планировщика используется {@code SCHEDULED}; остальные состояния
 * задают жизненный цикл обхода и заполняются логикой сбора (следующие инкременты).
 * Различение полного и частичного обхода (для семантики закрытия, A06) вводится
 * вместе с реальным сбором.</p>
 */
public enum CrawlRunState {
    SCHEDULED,
    RUNNING,
    COMPLETED,
    FAILED
}

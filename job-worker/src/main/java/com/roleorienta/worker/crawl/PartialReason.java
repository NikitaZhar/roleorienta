package com.roleorienta.worker.crawl;

/**
 * Причина неполного чтения источника (технический документ §5): хранится в обходе и видна в
 * показателях источников.
 */
public enum PartialReason {
    /** Упор в потолок страниц за одно чтение. */
    PAGE_LIMIT,
    /** Отказ или испорченный ответ страницы после первой. */
    PAGE_FAILED,
    /** Список кончился раньше объявленного источником числа публикаций. */
    LIST_ENDED_EARLY
}

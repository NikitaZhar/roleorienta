package com.roleorienta.worker.crawl;

/**
 * Конечное состояние обхода (технический документ §4).
 */
public enum CrawlRunState {
    /** Список прочитан полностью; только такой обход засчитывает отсутствие публикаций. */
    COMPLETE,
    /** Список прочитан неполно; сохранённые сведения не меняются. */
    PARTIAL,
    /** Источник не отдал список. */
    FAILED
}

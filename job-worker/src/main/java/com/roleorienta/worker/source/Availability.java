package com.roleorienta.worker.source;

/**
 * Доступность источника (технический документ §4, §9).
 */
public enum Availability {
    /** Последнее чтение получило ответ списка. */
    OK,
    /** Временные отказы, срок до «недоступен» не истёк. */
    TEMP_FAILING,
    /** Отказы дольше срока или постоянный отказ: кадровая страница требует перепроверки. */
    UNAVAILABLE
}

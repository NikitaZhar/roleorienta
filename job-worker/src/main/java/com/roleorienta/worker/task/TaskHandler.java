package com.roleorienta.worker.task;

/**
 * Обработчик заданий одного типа. Реализации — бины Spring; {@link TaskExecutor} выбирает
 * обработчик по {@link #type()}.
 *
 * <p>Обработчик должен быть идемпотентным: при сбое после выполнения работы задание может быть
 * выполнено повторно. Внешние запросы выполняются без открытой транзакции БД.</p>
 */
public interface TaskHandler {

    /**
     * @return тип заданий, которые обрабатывает этот обработчик
     */
    String type();

    /**
     * Выполняет задание.
     *
     * @param task захваченное задание
     * @return результат; исключение означает ошибку кода — задание завершается неудачей, сообщение
     *         уходит в DLQ
     */
    TaskOutcome handle(TaskRecord task);
}

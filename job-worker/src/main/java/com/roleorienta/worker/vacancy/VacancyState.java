package com.roleorienta.worker.vacancy;

/**
 * Состояние вакансии (бизнес-описание §4.3).
 */
public enum VacancyState {
    /** Хотя бы один источник подтверждает наличие. */
    ACTIVE,
    /** Ни один источник не подтвердил, но и оснований для закрытия нет. */
    NEEDS_RECHECK,
    /** Источник указал закрытие или подтверждено отсутствие. */
    CLOSED
}

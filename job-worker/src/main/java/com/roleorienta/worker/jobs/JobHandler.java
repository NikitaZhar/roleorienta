package com.roleorienta.worker.jobs;

/**
 * Обработчик фонового задания. Отделяет приём сообщения (слушатель, идемпотентность,
 * повторы) от собственно бизнес-обработки (§3.2, принцип инверсии зависимостей):
 * слушатель зависит от этой абстракции, а конкретные обработчики (сбор,
 * обнаружение, агрегация) добавляются отдельными реализациями по мере развития.
 */
public interface JobHandler {

    /**
     * Обрабатывает задание. Исключение означает неуспех: слушатель откатит
     * транзакцию, сообщение будет повторено, а после исчерпания попыток уйдёт в
     * DLQ. Обработчик должен быть безопасен к повторному вызову — на уровне
     * доставки гарантируется однократность через ключ идемпотентности, но сам
     * повтор в пределах попыток возможен.
     *
     * @param message разобранное задание
     */
    void handle(JobMessage message);
}

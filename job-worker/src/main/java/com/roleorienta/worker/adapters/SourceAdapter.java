package com.roleorienta.worker.adapters;

import com.roleorienta.core.domain.Source;

/**
 * Единый контракт адаптера источника (§5 техдока).
 *
 * <p>Один адаптер обслуживает все источники одной системы найма/площадки: он умеет
 * перечислить публикации в области источника (доска компании или область площадки)
 * с пагинацией. Обработчик задания зависит от этой абстракции, а не от конкретной
 * системы (принцип инверсии зависимостей, §3.2 боевого контракта); конкретные
 * реализации подключаются как отдельные бины и выбираются по коду провайдера
 * ({@link SourceAdapterRegistry}).</p>
 *
 * <p>Реализовано две части контракта §5: перечисление публикаций в области источника
 * ({@link #listPostings}) для задания {@code DISCOVER_PAGE} и получение детальной
 * страницы одной публикации ({@link #getPosting}) для задания {@code FETCH_POSTING}.
 * Возврат полностью структурированных требований — отдельный срез (§6).</p>
 */
public interface SourceAdapter {

    /**
     * Код провайдера, который обслуживает адаптер (напр. {@code greenhouse}).
     * Совпадает с {@code Provider.code} источника и служит ключом выбора адаптера.
     *
     * @return стабильный код провайдера
     */
    String providerCode();

    /**
     * Перечисляет публикации в области источника постранично.
     *
     * @param source источник сбора (адрес и параметры берутся из него)
     * @param cursor курсор страницы из предыдущего вызова или {@code null} для первой страницы
     * @return страница публикаций и курсор следующей страницы ({@code null}, если страниц больше нет)
     */
    PostingsPage listPostings(Source source, String cursor);

    /**
     * Получает детальную страницу одной публикации и возвращает добранные поля
     * (те, которых нет в ленте-списке; §5, «деталь из detail-endpoint, а не из
     * списка»). Поля возвращаются сырыми — нормализация выполняется в следующем срезе.
     *
     * @param source     источник сбора
     * @param externalId идентификатор публикации в терминах источника
     * @return добранные детальные поля публикации
     */
    FetchedPosting getPosting(Source source, String externalId);

    /**
     * Сообщает ли провайдер распределение публикаций по странам
     * ({@link PostingsPage#countryCounts()}). Если да, а распределение в ответе пустое,
     * рынок источника <b>не проверен</b> — гейт обнаружения не подключает его вслепую
     * (§58). Провайдеры без такого распределения (Greenhouse) — {@code false}.
     *
     * @return {@code true}, если адаптер заполняет {@code countryCounts}
     */
    default boolean reportsCountries() {
        return false;
    }
}

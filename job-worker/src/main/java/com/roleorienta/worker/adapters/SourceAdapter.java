package com.roleorienta.worker.adapters;

import com.roleorienta.core.domain.Source;

/**
 * Единый контракт адаптера источника (§5 техдока).
 *
 * <p>Один адаптер обслуживает все источники одной системы найма/площадки: он умеет
 * перечислить публикации в области источника (доска компании или область площадки)
 * с пагинацией. Обработчик задания зависит от этой абстракции, а не от конкретной
 * системы (принцип инверсии зависимостей, §3.2 боевого контракта); конкретные
 * реализации подключаются как отдельные бины и выбираются по коду провайдера
 * ({@link SourceAdapterRegistry}).</p>
 *
 * <p>Получение одной публикации и возврат структурированных полей (остальные части
 * контракта из §5) добавляются вместе с заданием {@code FETCH_POSTING} в следующем
 * инкременте — сейчас реализовано только перечисление, нужное для
 * {@code DISCOVER_PAGE}.</p>
 */
public interface SourceAdapter {

    /**
     * Код провайдера, который обслуживает адаптер (напр. {@code greenhouse}).
     * Совпадает с {@code Provider.code} источника и служит ключом выбора адаптера.
     *
     * @return стабильный код провайдера
     */
    String providerCode();

    /**
     * Перечисляет публикации в области источника постранично.
     *
     * @param source источник сбора (адрес и параметры берутся из него)
     * @param cursor курсор страницы из предыдущего вызова или {@code null} для первой страницы
     * @return страница публикаций и курсор следующей страницы ({@code null}, если страниц больше нет)
     */
    PostingsPage listPostings(Source source, String cursor);
}
